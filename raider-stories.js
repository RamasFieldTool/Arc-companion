// Raider Radio owns the surrounding UI; this layer keeps story prose/title/summary
// synchronized with the same document language used by the rest of the app.
(()=>{
  const stories=window.RFTCommunityStories||[];
  const supported=new Set(['de','en','fr','es']);
  const chrome={
    de:{kicker:'Community Story',credit:'Community Story von ',permission:'Mit Erlaubnis veröffentlicht.'},
    en:{kicker:'Community Story',credit:'Community Story by ',permission:'Published with permission.'},
    fr:{kicker:'Histoire de la communauté',credit:'Histoire de la communauté par ',permission:'Publiée avec autorisation.'},
    es:{kicker:'Historia de la comunidad',credit:'Historia de la comunidad de ',permission:'Publicada con permiso.'}
  };
  function activeLanguage(){
    const lang=document.documentElement.lang;
    return supported.has(lang)?lang:'en';
  }
  function localized(story,lang=activeLanguage()){
    const requested=story.translations?.[lang];
    const fallback=story.translations?.[story.originalLanguage||story.language]||story.translations?.de;
    return {lang,text:requested||fallback||{title:story.title,summary:story.summary,content:story.content}};
  }
  function storyFromHash(){
    const parts=location.hash.slice(1).split('/');
    if(parts[0]!=='raiderRadio'||parts[1]!=='stories'||!parts[2])return null;
    return stories.find(story=>encodeURIComponent(story.id)===parts[2])||null;
  }
  function replaceBody(body,content,lang){
    if(body.dataset.storyLanguage===lang&&body.dataset.storyContent===content)return;
    body.replaceChildren();
    content.split('\n\n').forEach(paragraph=>{
      const node=document.createElement('p');
      node.textContent=paragraph;
      body.append(node);
    });
    body.lang=lang;
    body.dataset.storyLanguage=lang;
    body.dataset.storyContent=content;
  }
  function applyStoryLanguage(){
    const lang=activeLanguage();
    document.querySelectorAll('.fan-story-card[data-story-id]').forEach(card=>{
      const story=stories.find(entry=>entry.id===card.dataset.storyId);
      if(!story)return;
      const local=localized(story,lang).text;
      const title=card.querySelector('.fan-story-card-title');
      const summary=card.querySelector('.fan-story-summary');
      const read=card.querySelector('.fan-story-read');
      if(title){title.textContent=local.title;title.lang=lang;}
      if(summary){summary.textContent=local.summary;summary.lang=lang;}
      if(read)read.setAttribute('aria-label',`${read.textContent}: ${local.title}`);
    });

    const story=storyFromHash();
    const detail=document.querySelector('.fan-story-detail');
    if(!story||!detail||!detail.childElementCount)return;
    const local=localized(story,lang).text;
    const labels=chrome[lang]||chrome.en;
    const title=detail.querySelector('.fan-story-title');
    const kicker=detail.querySelector('.fan-story-kicker');
    const body=detail.querySelector('.fan-story-body');
    const credit=detail.querySelector('.fan-story-credit');
    if(title){title.textContent=local.title;title.lang=lang;}
    if(kicker)kicker.textContent=labels.kicker;
    if(body)replaceBody(body,local.content,lang);
    if(credit){
      credit.lang=lang;
      const paragraphs=credit.querySelectorAll('p');
      if(paragraphs[0])paragraphs[0].textContent=labels.credit+story.author;
      if(paragraphs[1])paragraphs[1].textContent=labels.permission;
    }
    detail.dataset.storyLanguage=lang;
  }
  let scheduled=false;
  function schedule(){
    if(scheduled)return;
    scheduled=true;
    requestAnimationFrame(()=>{scheduled=false;applyStoryLanguage();});
  }
  new MutationObserver(schedule).observe(document.documentElement,{attributes:true,attributeFilter:['lang']});
  window.addEventListener('hashchange',schedule);
  window.RFTApplyStoryLanguage=applyStoryLanguage;
  if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',schedule,{once:true});
  else schedule();
})();
